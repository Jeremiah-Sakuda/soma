// Bundles the 3D lift renderer and the parts of three.js it uses into one classic script,
// since the sandboxed overlay page loads only local scripts and no ES modules.
const path = require('node:path');
(async () => {
  const { build } = await import(require.resolve('rolldown', { paths: [path.resolve(__dirname, '..')] }));
  await build({
    input: path.join(__dirname, 'lift-entry.mjs'),
    resolve: { modules: [path.resolve(__dirname, '../node_modules')], alias: { '@': path.resolve(__dirname, '../src') } },
    output: { file: path.join(__dirname, 'point-overlay-3d.js'), format: 'iife', minify: true, banner: '/* Soma 3D lift. Bundles three.js (MIT, © 2010-2026 three.js authors). Generated by build-lift.cjs; edit lift-renderer.mjs and lift-model.mjs. */' },
    logLevel: 'warn',
  });
  console.log('Built point-overlay-3d.js');
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
