const OPERATIONS = new Set([
  'bootstrap',
  'status',
  'save-fill',
  'fill',
  'forget',
  'allocate',
  'rotate',
  'release',
  'cancel',
  'sweep',
  'unknown',
]);
const STATUSES = new Set([400, 401, 403, 404, 409, 413, 415, 429, 503]);
export function credentialFailureFacts(error, operation = 'unknown') {
  return Object.freeze({
    event: 'credential_operation_failed',
    operation: OPERATIONS.has(operation) ? operation : 'unknown',
    code: CODES.has(error?.code) ? error.code : 'credential_unavailable',
    status: STATUSES.has(error?.status) ? error.status : 503,
  });
}
